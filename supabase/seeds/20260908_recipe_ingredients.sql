  if exists (
    select 1
    from recipe_ingredient_seed_data seed
    left join public.recipes recipe on recipe.source_key = seed.recipe_source_key
    left join public.ingredients ingredient on ingredient.source_key = seed.ingredient_source_key
    where recipe.id is null or ingredient.id is null
  ) then
    raise exception 'Recipe- of Ingredient-ID ontbreekt; seed is niet uitgevoerd.';
  end if;
  if (
    select count(distinct recipe_source_key)
    from recipe_ingredient_seed_data
  ) <> 100 then
    raise exception 'Niet alle recepten hebben ingrediëntrelaties.';
  end if;
end $$;

insert into public.recipe_ingredients (
  recipe_id, ingredient_id, amount_per_person, unit, position
)
select recipe.id, ingredient.id, seed.amount_per_person, seed.unit, seed.position
from recipe_ingredient_seed_data seed
join public.recipes recipe on recipe.source_key = seed.recipe_source_key
join public.ingredients ingredient on ingredient.source_key = seed.ingredient_source_key
on conflict (recipe_id, position) do update set
  ingredient_id = excluded.ingredient_id,
  amount_per_person = excluded.amount_per_person,
  unit = excluded.unit,
  updated_at = now();

commit;
